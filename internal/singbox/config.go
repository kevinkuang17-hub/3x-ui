// Package singbox runs the protocols Xray does not have (AnyTLS, NaiveProxy) in one sing-box
// sidecar. Each user's traffic leaves sing-box through a loopback SOCKS5 inbound in Xray that is
// authenticated as the client's email, so Xray still meters, limits and routes it per client.
package singbox

import (
	"crypto/rand"
	"encoding/base64"
	"encoding/json"
	"fmt"
	"slices"
	"sync"
)

// Protocols served by the sidecar, as stored on the inbound.
const (
	AnyTLS = "anytls"
	Naive  = "naive"
)

// RelayBasePort is below TUIC's (64001..65000) and AmneziaWG's (65101..) relay windows.
const (
	RelayBasePort = 63000
	relaySlots    = 1000
)

// RelayPortForInbound is the loopback port of the Xray SOCKS5 inbound behind one sidecar inbound.
func RelayPortForInbound(inboundID int) int {
	return RelayBasePort + 1 + (inboundID-1)%relaySlots
}

var (
	relayPasswordOnce sync.Once
	relayPassword     string
)

// RelayPassword authenticates sing-box to the loopback relays; it only has to be unguessable by
// other local processes, and both ends are generated by this process.
func RelayPassword() string {
	relayPasswordOnce.Do(func() {
		var b [24]byte
		_, _ = rand.Read(b[:])
		relayPassword = base64.RawURLEncoding.EncodeToString(b[:])
	})
	return relayPassword
}

// User is one client: Name is the email, which is also the relay's SOCKS user.
type User struct {
	Name     string
	Password string
}

// Instance is one AnyTLS or NaiveProxy inbound to serve.
type Instance struct {
	Id         int
	Tag        string
	Protocol   string
	Listen     string
	Port       int
	ServerName string
	CertFile   string
	KeyFile    string
	Users      []User
}

type tlsOptions struct {
	Enabled         bool     `json:"enabled"`
	ServerName      string   `json:"server_name,omitempty"`
	ALPN            []string `json:"alpn,omitempty"`
	CertificatePath string   `json:"certificate_path"`
	KeyPath         string   `json:"key_path"`
}

// Build renders the sing-box configuration: one inbound per instance, one SOCKS5 outbound per
// user into that inbound's relay, and a final reject so an unmatched connection never goes out.
func Build(insts []Instance, relayPass string) ([]byte, error) {
	insts = slices.Clone(insts)
	slices.SortFunc(insts, func(a, b Instance) int { return a.Id - b.Id })
	inbounds := []map[string]any{}
	outbounds := []map[string]any{}
	rules := []map[string]any{}
	tags := []string{}
	for _, in := range insts {
		listen := in.Listen
		if listen == "" {
			listen = "::"
		}
		tls := tlsOptions{Enabled: true, ServerName: in.ServerName, CertificatePath: in.CertFile, KeyPath: in.KeyFile}
		inbound := map[string]any{"type": in.Protocol, "tag": in.Tag, "listen": listen, "listen_port": in.Port}
		switch in.Protocol {
		case AnyTLS:
			users := make([]map[string]string, 0, len(in.Users))
			for _, u := range in.Users {
				users = append(users, map[string]string{"name": u.Name, "password": u.Password})
			}
			inbound["users"] = users
		case Naive:
			users := make([]map[string]string, 0, len(in.Users))
			for _, u := range in.Users {
				users = append(users, map[string]string{"username": u.Name, "password": u.Password})
			}
			inbound["users"] = users
			inbound["network"] = "tcp"
			tls.ALPN = []string{"h2", "http/1.1"}
		default:
			return nil, fmt.Errorf("sing-box: unsupported protocol %q", in.Protocol)
		}
		inbound["tls"] = tls
		inbounds = append(inbounds, inbound)
		tags = append(tags, in.Tag)
		for i, u := range in.Users {
			out := fmt.Sprintf("relay-%d-%d", in.Id, i)
			outbounds = append(outbounds, map[string]any{
				"type": "socks", "tag": out, "server": "127.0.0.1", "server_port": RelayPortForInbound(in.Id),
				"version": "5", "username": u.Name, "password": relayPass,
			})
			rules = append(rules, map[string]any{"inbound": []string{in.Tag}, "auth_user": []string{u.Name}, "outbound": out})
		}
	}
	if len(tags) > 0 {
		rules = append(rules, map[string]any{"inbound": tags, "action": "reject"})
	}
	cfg := map[string]any{
		"log":       map[string]any{"level": "warn", "timestamp": true},
		"inbounds":  inbounds,
		"outbounds": outbounds,
		"route":     map[string]any{"rules": rules},
	}
	return json.MarshalIndent(cfg, "", "  ")
}
